#!/usr/bin/env python3
"""Generate the guest->native D3D9 COM bridge from dxvk's d3d9.h (Wine-style headers).
Usage: gen_d3d9.py <d3d9.h> <out.cpp>

Every interface method becomes a typed C++ forwarder: read the guest's 32-bit stdcall arguments (this = first stack
argument), convert them, call the native dxvk object, convert the result, pop the arguments. Methods that need real
translation (struct layouts with pointers/handles, Lock staging, object lifetime) call hand-written special_* functions
in runtime/host/d3d9_bridge.cpp instead."""
import re, sys

SPECIAL = {"QueryInterface", "Release", "CreateDevice", "CreateDeviceEx", "Reset", "ResetEx", "CreateAdditionalSwapChain",
           "GetPresentParameters", "GetCreationParameters", "LockRect", "UnlockRect", "Lock", "Unlock", "LockBox",
           "UnlockBox", "GetDC", "ReleaseDC", "GetAdapterMonitor", "GetContainer"}


def parse(text):
    """-> [(iface, [(ret, name, [(ctype, pname)])])] in header order (each block lists inherited methods too)."""
    out = []
    for m in re.finditer(r"DECLARE_INTERFACE_\(\s*(\w+)\s*,\s*\w+\s*\)\s*\{(.*?)\n\};", text, re.S):
        iface, body = m.group(1), m.group(2)
        if any(iface == o[0] for o in out): continue
        meths = []
        for d in re.finditer(r"STDMETHOD(?:_\(\s*([^,]+?)\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\(\s*THIS_?\s*(.*?)\)\s*PURE\s*;", body, re.S):
            ret = d.group(1) or "HRESULT"
            name = d.group(2) or d.group(3)
            raw = " ".join(d.group(4).split())
            params = []
            for k, p in enumerate(x.strip() for x in raw.split(",") if x.strip()):
                pm = re.match(r"(.*?[\s*])(\w+)$", p)
                # a few declarations name only the type (e.g. "void*"): invent a parameter name
                params.append((pm.group(1).strip(), pm.group(2)) if pm else (p, f"p{k}"))
            meths.append((ret.strip(), name, params))
        out.append((iface, meths))
    return out


# some dxvk declarations say "struct IDirect3DDevice9**": the struct keyword is ignored everywhere
def is_iface(t): return re.match(r"^(const\s+)?(struct\s+)?(IDirect3D\w*9(Ex)?|IUnknown)\s*\*$", t) is not None
def is_iface_out(t): return re.match(r"^(struct\s+)?(IDirect3D\w*9(Ex)?|IUnknown)\s*\*\*$", t) is not None
def base(t): return re.sub(r"[\s*]|const|struct\s", "", t)


def gen_method(iface, ti, ret, name, params, ifaces):
    fn = f"m_{iface}_{name}"
    lines = [f"static void {fn}(CPU *c) {{"]
    if name in SPECIAL:
        lines += [f"    special_{name}(c, T_{iface});", "}"]
        return fn, "\n".join(lines)
    lines.append(f"    auto *self = ({iface} *)nat(ARG(c, 0));")
    lines.append(f"    if (!self) die(\"d3d9: {iface}::{name} on a dead object %08x\", ARG(c, 0));")
    slot, call, post = 1, [], []
    for t, n in params:
        a = f"ARG(c, {slot})"
        bt = base(t)
        if is_iface_out(t):
            lines.append(f"    {bt} *o_{n} = nullptr; uint32_t g_{n} = {a};")
            call.append(f"g_{n} ? &o_{n} : nullptr")
            ty = f"T_{bt}" if bt in ifaces else "-1"
            post.append(f"    if (g_{n}) U32(g_{n}) = wrap(o_{n}, {ty});")
        elif is_iface(t):
            call.append(f"({t})nat({a})")
        elif bt in ("REFIID", "REFGUID"):
            call.append(f"*(const GUID *)GM({a})")
        elif bt == "HWND":
            call.append(f"native_hwnd({a})")
        elif bt in ("HANDLE",) and "*" in t:
            call.append("nullptr")   # pSharedHandle: must be NULL on D3D9 (non-Ex)
        elif "**" in t:
            lines.append(f"    die(\"d3d9: {iface}::{name}: unhandled out-pointer {t}\");")
            call.append("nullptr")
        elif "*" in t:
            call.append(f"({t})hptr({a})")
        elif bt in ("float", "FLOAT"):
            call.append(f"V(GM(REG(c, R_ESP) + 4 + 4 * {slot}), float)")
        else:
            call.append(f"({t}){a}")
        slot += 1
    call_s = f"self->{name}({', '.join(call)})"
    if ret == "void":
        lines.append(f"    {call_s};")
        lines += post + [f"    ret_std(c, 0, {slot});"]
    elif ret in ("float", "FLOAT"):
        lines.append(f"    float r = {call_s};")
        lines += post + ["    ret_st0(c, r);", f"    ret_std(c, REG(c, R_EAX), {slot});"]
    else:
        lines.append(f"    auto r = {call_s};")
        lines += post + [f"    ret_std(c, (uint32_t)r, {slot});"]
    lines.append("}")
    return fn, "\n".join(lines)


def main():
    text = open(sys.argv[1]).read()
    ifaces = parse(text)
    names = [i for i, _ in ifaces]
    out = ["// GENERATED by tools/recomp/gen_d3d9.py from dxvk's d3d9.h - do not edit.",
           '#include "d3d9_bridge.h"', ""]
    out.append("enum {" + ", ".join(f"T_{n} = {k}" for k, n in enumerate(names)) + f", T_COUNT = {len(names)} }};")
    out.append("const char *const iface_names[] = {" + ", ".join(f'"{n}"' for n in names) + "};")
    out.append("const int iface_count = T_COUNT;")
    tables = []
    for ti, (iface, meths) in enumerate(ifaces):
        fns = []
        for ret, name, params in meths:
            fn, code = gen_method(iface, ti, ret, name, params, set(names))
            out.append(code)
            fns.append(fn)
        tables.append((iface, fns, [m[1] for m in meths]))
    for iface, fns, mnames in tables:
        out.append(f"static const Fn tbl_{iface}[] = {{{', '.join(fns)}}};")
        out.append(f"static const char *const mn_{iface}[] = {{{', '.join(chr(34) + m + chr(34) for m in mnames)}}};")
    out.append("const Fn *const iface_methods[] = {" + ", ".join(f"tbl_{i}" for i, _, _ in tables) + "};")
    out.append("const char *const *const iface_method_names[] = {" + ", ".join(f"mn_{i}" for i, _, _ in tables) + "};")
    out.append("const int iface_method_count[] = {" + ", ".join(str(len(f)) for _, f, _ in tables) + "};")
    out.append("int iface_type(const char *name) { for (int i = 0; i < T_COUNT; i++) if (!strcmp(iface_names[i], name)) return i; return -1; }")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")
    print(f"{len(ifaces)} interfaces, {sum(len(m) for _, m in ifaces)} methods -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
